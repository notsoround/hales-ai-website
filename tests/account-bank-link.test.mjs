import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { homedir, tmpdir } from 'node:os';
import { mkdtempSync, realpathSync, rmSync } from 'node:fs';
import path from 'node:path';
import { createServer } from 'vite';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || path.join(homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
const cacheDir = mkdtempSync(path.join(tmpdir(), 'bank-link-fixture-'));
const server = await createServer({ cacheDir, define: { 'import.meta.env.VITE_CUPCAKE_ACCOUNT_SESSIONS': '"true"' },
  plugins: [{ name: 'bank-link-fixture', configureServer(vite) { vite.middlewares.use((req, _res, next) => {
    if (req.url?.split('?')[0] === '/cupcake/account') req.url = '/tests/account-bank-link-preview.html' + (req.url.includes('?') ? '?' + req.url.split('?')[1] : '');
    next();
  }); } }], server: { host: '127.0.0.1', port: 0, hmr: false, fs: { allow: [process.cwd(), realpathSync('node_modules')] } } });
await server.listen();
const base = server.resolvedUrls.local[0];
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
  const outside = [], errors = [];
  await context.route('**/*', route => {
    const url = new URL(route.request().url());
    if (url.origin === new URL(base).origin || url.protocol === 'data:') return route.continue();
    outside.push(url.origin); return route.abort();
  });
  const page = await context.newPage(); page.setDefaultTimeout(10000);
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + 'cupcake/account');
  assert.equal(await page.evaluate(() => window.bankFixture.calls.length), 0);
  await page.getByRole('button', { name: 'Check bank connections' }).click();
  await page.getByText('No bank is connected to this account.').waitFor();
  await page.getByRole('button', { name: 'Connect a bank' }).click();
  await page.waitForFunction(() => window.bankFixture.opened === 1);
  const previous = await page.evaluate(() => window.bankFixture.calls.find(call => call.action === 'bank_link_create'));
  assert.equal(previous.owner, 'acc_bank_a');
  await page.goto(base + 'cupcake/account?oauth_state_id=synthetic-state');
  await page.waitForFunction(() => window.bankFixture.opened === 1);
  assert.match(await page.evaluate(() => window.bankFixture.returnedUri), /\/cupcake\/account\?oauth_state_id=synthetic-state$/);
  assert.equal(await page.evaluate(() => window.bankFixture.token), 'synthetic-link-token');
  await page.evaluate(() => window.bankFixture.success('synthetic-public-token'));
  await page.getByText('Bank connected and transactions refreshed.').waitFor();
  const exchange = await page.evaluate(() => window.bankFixture.calls.find(call => call.action === 'bank_link_exchange'));
  assert.equal(exchange.owner, 'acc_bank_a'); assert.equal(exchange.body.request_id, previous.body.request_id);
  assert.equal(new URL(page.url()).searchParams.has('oauth_state_id'), false);
  await page.getByRole('button', { name: 'Refresh transactions' }).click();
  await page.getByText('Transaction refresh completed.').waitFor();
  assert.equal(await page.evaluate(() => window.bankFixture.calls.filter(call => call.action === 'bank_sync').length), 2);
  await page.evaluate(() => window.setBankNeedsReconnect());
  await page.getByRole('button', { name: 'Refresh status' }).click();
  await page.getByRole('button', { name: 'Reconnect bank' }).click();
  await page.waitForFunction(() => window.bankFixture.token === 'synthetic-update-token');
  await page.evaluate(() => window.bankFixture.success(null));
  await page.getByText('Bank reconnected and transactions refreshed.').waitFor();
  assert.equal(await page.evaluate(() => window.bankFixture.calls.filter(call => call.action === 'bank_link_update_complete').length), 1);
  assert.equal(await page.evaluate(() => window.bankFixture.calls.filter(call => call.action === 'bank_sync').length), 2, 'reconnect completion performs its own sync');
  await page.getByRole('button', { name: 'Connect a bank' }).click();
  await page.waitForFunction(() => window.bankFixture.opened === 3);
  await page.evaluate(() => { window.bankFixture.failExchange = true; window.bankFixture.success('synthetic-other-token'); });
  await page.getByText('The connection could not be confirmed. Check status before starting another connection.').waitFor();
  assert.equal(await page.getByRole('button', { name: 'Connect a bank' }).isDisabled(), true, 'an uncertain exchange cannot be silently repeated');
  await page.getByRole('button', { name: 'Refresh status' }).click();
  await page.getByText('Bank connection confirmed. Refresh transactions to use it for receipt matching.').waitFor();
  assert.equal(await page.getByRole('button', { name: 'Connect a bank' }).isEnabled(), true);
  await page.getByRole('button', { name: 'Disconnect bank' }).click();
  await page.getByRole('alertdialog', { name: 'Disconnect bank?' }).getByRole('button', { name: 'Cancel' }).click();
  assert.equal(await page.evaluate(() => window.bankFixture.calls.filter(call => call.action === 'bank_disconnect').length), 0);
  await page.getByRole('button', { name: 'Disconnect bank' }).click();
  await page.getByRole('alertdialog', { name: 'Disconnect bank?' }).getByRole('button', { name: 'Disconnect' }).click();
  await page.getByText('Bank disconnected.').waitFor();
  assert.equal(await page.evaluate(() => window.bankFixture.calls.filter(call => call.action === 'bank_disconnect').length), 1);
  const beforeSwitch = await page.evaluate(() => window.bankFixture.calls.length);
  await page.evaluate(() => window.switchOwner('B'));
  await page.getByRole('button', { name: 'Connect a bank' }).click();
  assert.equal(await page.evaluate(() => window.bankFixture.calls.length), beforeSwitch, 'a stale component cannot link another account');
  assert.deepEqual(outside, []); assert.deepEqual(errors, []);
  await context.close();
  const retryContext = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
  await retryContext.route('**/*', route => new URL(route.request().url()).origin === new URL(base).origin ? route.continue() : route.abort());
  const retryPage = await retryContext.newPage(); retryPage.setDefaultTimeout(10000);
  await retryPage.goto(base + 'cupcake/account');
  await retryPage.getByRole('button', { name: 'Check bank connections' }).click();
  await retryPage.getByRole('button', { name: 'Connect a bank' }).click();
  await retryPage.waitForFunction(() => window.bankFixture.opened === 1);
  await retryPage.evaluate(() => { window.bankFixture.failExchange = true; window.bankFixture.success('synthetic-lost-token'); });
  await retryPage.getByRole('alert').waitFor();
  await retryPage.reload();
  await retryPage.getByRole('button', { name: 'Check bank connections' }).click();
  assert.equal(await retryPage.getByRole('button', { name: 'Connect a bank' }).isDisabled(), true, 'an unresolved exchange remains fenced after reload');
  await retryContext.close();
  console.log('PASS: synthetic account-scoped Plaid start, OAuth resume, exchange and refresh with no real bank');
} finally { await browser.close(); await server.close(); rmSync(cacheDir, { recursive: true, force: true }); }
