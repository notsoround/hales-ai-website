import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { homedir, tmpdir } from 'node:os';
import { mkdtempSync, realpathSync, rmSync } from 'node:fs';
import path from 'node:path';
import { createServer } from 'vite';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || path.join(homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
const cacheDir = mkdtempSync(path.join(tmpdir(), 'cupcake-food-review-'));
const server = await createServer({ cacheDir, plugins: [{ name: 'synthetic-media-root', configureServer(server) { server.middlewares.use((req, _res, next) => { if (['/cupcake/account', '/cupcake'].includes(req.url?.split('?')[0])) req.url = '/tests/account-media-preview.html'; next(); }); } }], define: { 'import.meta.env.VITE_CUPCAKE_ACCOUNT_SESSIONS': '"true"' }, server: { host: '127.0.0.1', port: 0, hmr: false, fs: { allow: [process.cwd(), realpathSync('node_modules')] } } });
await server.listen();
const base = `http://127.0.0.1:${server.httpServer.address().port}`;
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
page.setDefaultTimeout(10000);
await page.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort());
try {
  await page.goto(base + '/cupcake/account?review-tools=1');
  await page.getByRole('heading', { name: 'Food', exact: true }).waitFor();
  const review = page.locator('details.nx-food-review');
  const reads = () => page.evaluate(() => window.mediaFixture.requests.filter(r => r.action === 'food_review_list').length);
  const writes = () => page.evaluate(() => window.mediaFixture.requests.filter(r => r.action === 'food_review_resolve'));
  assert.equal(await reads(), 0);
  await review.locator(':scope > summary').click();
  await review.getByRole('heading', { name: '2 photos to check' }).waitFor();
  const row = desc => review.getByRole('button', { name: new RegExp(desc) });
  const dialog = page.getByRole('dialog', { name: 'Review photo' });
  await row('Synthetic pending lunch').click();
  await dialog.getByAltText('Photo under review').waitFor();
  const attach = dialog.getByRole('button', { name: 'Attach to meal' });
  assert.equal(await attach.isEnabled(), false);
  assert.equal(await dialog.getByRole('option', { name: /Synthetic saved lunch/ }).count(), 0);
  await dialog.getByLabel('Logged meal').selectOption({ label: await dialog.getByRole('option', { name: /Synthetic manual dinner/ }).innerText() });
  assert.equal((await writes()).length, 0);
  await attach.click();
  await review.getByText('Photo attached to the logged meal.', { exact: true }).waitFor();
  await review.getByRole('heading', { name: '1 photo to check' }).waitFor();
  await row('Synthetic failed photo').click();
  assert.equal(await dialog.getByLabel('Logged meal').isEnabled(), false);
  await dialog.getByRole('button', { name: 'Not food', exact: true }).click();
  await review.getByRole('heading', { name: 'No photos to check' }).waitFor();
  await review.getByText('Reviewed photos (2)', { exact: true }).click();
  await row('Synthetic failed photo').click();
  await dialog.getByRole('button', { name: 'Undo', exact: true }).click();
  await review.getByRole('heading', { name: '1 photo to check' }).waitFor();
  await row('Synthetic pending lunch').click();
  await dialog.getByRole('button', { name: 'Undo', exact: true }).click();
  await review.getByRole('heading', { name: '2 photos to check' }).waitFor();
  const commands = await writes();
  assert.deepEqual(commands.map(row => row.resolution), ['attach', 'not_food', 'undo', 'undo']);
  assert.equal(commands[0].targetMealId, 'meal_' + 'd'.repeat(32));
  assert.ok(commands.slice(1).every(row => !('targetMealId' in row)));
  assert.equal(await page.evaluate(() => window.mediaFixture.photoUploads.length), 0);
  await page.goto(base + '/cupcake/account');
  await review.locator(':scope > summary').click();
  await review.getByText('Photo review tools are not available yet.', { exact: false }).waitFor();
  await row('Synthetic pending lunch').waitFor();
  assert.equal(await review.getByRole('button', { name: 'Not food' }).count(), 0);
  console.log('PASS: account review opens on demand; attaches only to a selected meal without a photo, supports Not food and both Undo paths, and falls back to read-only rows on old servers. Synthetic data only.');
} finally {
  await browser.close();
  await server.close();
  rmSync(cacheDir, { recursive: true, force: true });
}
